#!/usr/bin/env python3
"""Prepare a reviewed tweakcn preset for system appearance (Python 3.10+).

This is a development tool, not a runtime CSS importer or CSS security validator.
"""
import argparse
from pathlib import Path
import re


def render(source: str) -> str:
    """Keep the export intact and add its dark declarations under OS selection."""
    blocks = re.findall(r"(?:^|\n)\.dark\s*\{([^{}]*)\}", source)
    if len(blocks) != 1 or not re.search(r"(?:^|\n):root\s*\{", source):
        raise ValueError("Expected a reviewed :root and a single flat .dark block")
    return (
        "/* Generated by assets/theme/prepare.py; edit preset.css. */\n"
        + source.rstrip()
        + "\n\n@media (prefers-color-scheme: dark) {\n  :root {"
        + blocks[0]
        + "  }\n}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parent
    result = render((directory / "preset.css").read_text())
    target = directory / "runtime.css"
    if args.check:
        if not target.exists() or target.read_text() != result:
            parser.exit(1, "Theme output is stale; run assets/theme/prepare.py\n")
        print("Shared theme output matches preset.css")
    else:
        target.write_text(result)
        print(target)


if __name__ == "__main__":
    main()
